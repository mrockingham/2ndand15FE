export type SupportedTeamAbbreviation = keyof typeof teamVisualConfigs;

export const getTeamVisualConfig = (
  abbreviation: string | null | undefined,
): TeamVisualConfig | null => {
  if (!abbreviation) return null;
  const normalized = abbreviation.trim().toUpperCase();
  return normalized in teamVisualConfigs
    ? teamVisualConfigs[normalized as SupportedTeamAbbreviation]
    : null;
};
